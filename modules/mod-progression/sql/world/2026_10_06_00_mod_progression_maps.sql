-- mod-progression: the patch each map arrived in. Characters in an earlier patch can't enter it, queue
-- for it in the Dungeon Finder, or (battlegrounds and arenas) queue for it. Maps not listed are open from
-- 1.1. Arenas need the first patch with an arena season, and random battlegrounds and random dungeons
-- need 3.3; those are worked out in the module.

DROP TABLE IF EXISTS `progression_map`;
CREATE TABLE `progression_map` (
  `map` INT UNSIGNED NOT NULL COMMENT 'Map.dbc id',
  `patch` TINYINT UNSIGNED NOT NULL COMMENT 'progression_patch.id it arrived in',
  `comment` VARCHAR(64) NOT NULL DEFAULT '',
  PRIMARY KEY (`map`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

